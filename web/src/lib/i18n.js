// French typography: a narrow no-break space before ? ! : ; and inside « ».
function frenchSpaces(value) {
  if (typeof value === 'string') {
    return value.replace(/ ([?!:;])/g, ' $1').replace(/« /g, '« ').replace(/ »/g, ' »');
  }
  if (typeof value === 'function') return (...args) => frenchSpaces(value(...args));
  if (Array.isArray(value)) return value.map(frenchSpaces);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, frenchSpaces(v)]));
  return value;
}

